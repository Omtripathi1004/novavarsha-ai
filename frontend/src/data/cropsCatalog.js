/**
 * Centrally computes the top 3 optimal crops for any Indian location/state
 * Guaranteed identical results across Homepage Top 3 Cards and Voice Bulletin Player
 */
export function getTopCropsForLocation(stateName, hubState) {
  const stateQuery = (stateName || '').toLowerCase().trim();
  const hubQuery = (hubState || '').toLowerCase().trim();

  const stateMatched = INDIAN_CROPS_CATALOG.filter(c => 
    c.states.some(s => {
      const sLower = s.toLowerCase();
      return (stateQuery && sLower.includes(stateQuery)) || 
             (hubQuery && sLower.includes(hubQuery)) ||
             (stateQuery && stateQuery.includes(sLower));
    })
  );

  const pool = stateMatched.length >= 3 ? stateMatched : INDIAN_CROPS_CATALOG;
  return [...pool].sort((a, b) => b.suitability - a.suitability).slice(0, 3);
}

